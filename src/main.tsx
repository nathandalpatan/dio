function speechLabel(speech: TtsState, voice?: Voice) {
  if (speech.status === 'notInstalled') return speech.message || 'Voice not installed';
  if (speech.status === 'downloading') return `Downloading voice ${Math.round(speech.progress * 100)}%`;
  if (speech.status === 'loading') return 'Loading voice…';
  if (speech.status === 'synthesizing') return 'Preparing speech…';
  if (speech.status === 'error') return speech.message;
  if (speech.status === 'disabled') return '';
  return `Kokoro voice · ${accentName[voice?.accent || 'us']}`;
}
